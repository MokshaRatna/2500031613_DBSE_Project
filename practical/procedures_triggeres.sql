-- PROCEDURE 1: NO PARAMETERS
DELIMITER //
CREATE PROCEDURE GetAllEmployees()
BEGIN
    SELECT ENAME, JOB, SAL
    FROM EMP;
END //
DELIMITER ;
-- PROCEDURE 2: IN PARAMETER
DELIMITER //
CREATE PROCEDURE GetEmployeesByDept(IN p_deptno INT)
BEGIN
    SELECT ENAME, JOB, SAL
    FROM EMP
    WHERE DEPTNO = p_deptno;
END //
DELIMITER ;
-- PROCEDURE 3: OUT PARAMETER
DELIMITER //
CREATE PROCEDURE GetDeptSalaryTotal(
    IN p_deptno INT,
    OUT p_total DECIMAL(10,2)
)
BEGIN
    SELECT SUM(SAL) INTO p_total
    FROM EMP
    WHERE DEPTNO = p_deptno;
END //
DELIMITER ;
-- PROCEDURE 4: IF STATEMENT
DELIMITER //
CREATE PROCEDURE GiveRaise(
    IN p_empno INT,
    IN p_pct DECIMAL(5,2)
)
BEGIN
    DECLARE v_sal DECIMAL(7,2);
    SELECT SAL INTO v_sal
    FROM EMP
    WHERE EMPNO = p_empno;
    IF v_sal < 2000 THEN
        UPDATE EMP
        SET SAL = SAL + (SAL * p_pct / 100)
        WHERE EMPNO = p_empno;
    ELSE
        UPDATE EMP
        SET SAL = SAL + (SAL * (p_pct / 2) / 100)
        WHERE EMPNO = p_empno;
    END IF;
END //
DELIMITER ;
-- TRIGGER 1: BEFORE INSERT
DELIMITER //
CREATE TRIGGER trg_check_salary
BEFORE INSERT ON EMP
FOR EACH ROW
BEGIN
    IF NEW.SAL < 0 THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Salary cannot be negative';
    END IF;
END //
DELIMITER ;
-- AUDIT TABLE
CREATE TABLE EMP_AUDIT (
    audit_id INT AUTO_INCREMENT PRIMARY KEY,
    empno INT,
    old_sal DECIMAL(7,2),
    new_sal DECIMAL(7,2),
    changed_on DATETIME
);
-- TRIGGER 2: AFTER UPDATE
DELIMITER //
CREATE TRIGGER trg_log_sal_change
AFTER UPDATE ON EMP
FOR EACH ROW
BEGIN
    IF OLD.SAL <> NEW.SAL THEN
        INSERT INTO EMP_AUDIT(
            empno,
            old_sal,
            new_sal,
            changed_on
        )
        VALUES (
            OLD.EMPNO,
            OLD.SAL,
            NEW.SAL,
            NOW()
        );
    END IF;
END //
DELIMITER ;
-- TRIGGER 3: BEFORE DELETE
DELIMITER //
CREATE TRIGGER trg_prevent_manager_delete
BEFORE DELETE ON EMP
FOR EACH ROW
BEGIN
    IF OLD.JOB = 'PRESIDENT' THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Cannot delete the president record';
    END IF;
END //
DELIMITER ;
